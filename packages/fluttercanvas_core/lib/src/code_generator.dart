import 'breakpoints.dart';
import 'canvas_document.dart';
import 'code_emitter.dart';
import 'colors.dart';
import 'widget_catalog.dart';
import 'widget_node.dart';

/// Turns a [CanvasDocument] into a self-contained Flutter screen.
///
/// The output only imports `package:flutter/material.dart`. Responsive
/// helpers are added as private classes at the bottom of the file when the
/// design uses them, so the code has no dependency on FlutterCanvas.
class FlutterCodeGenerator {
  const FlutterCodeGenerator();

  /// Generates a complete Dart file for [document].
  String generate(CanvasDocument document) => _Session().generate(document);

  /// Converts a screen name such as `my home page` into `MyHomePage`.
  static String className(String raw) {
    final words = raw
        .split(RegExp(r'[^A-Za-z0-9]+'))
        .where((word) => word.isNotEmpty);
    final name = words
        .map((word) => word[0].toUpperCase() + word.substring(1))
        .join();
    if (name.isEmpty) return 'GeneratedScreen';
    if (RegExp(r'^[0-9]').hasMatch(name)) return 'Screen$name';
    return name;
  }

  /// Suggested file name for a screen, such as `my_home_page.dart`.
  static String fileName(String raw) {
    final snake = className(raw)
        .replaceAllMapped(RegExp(r'(?<=[a-z0-9])[A-Z]'), (m) => '_${m[0]}')
        .toLowerCase();
    return '$snake.dart';
  }
}

class _Session {
  bool _usesAdaptiveRow = false;
  bool _usesGrid = false;

  String generate(CanvasDocument document) {
    final name = FlutterCodeGenerator.className(document.name);
    // The root sits on a line indented 9 levels deep in the template below.
    final root = _node(document.root).render(9);
    final background = _color(document.backgroundColor);

    final buffer = StringBuffer()
      ..writeln("import 'package:flutter/material.dart';")
      ..writeln()
      ..writeln('/// Generated by FlutterCanvas.')
      ..writeln('///')
      ..writeln('/// Adapts to phones, tablets, desktop and the web.')
      ..writeln('class $name extends StatelessWidget {')
      ..writeln('  const $name({super.key});')
      ..writeln()
      ..writeln('  @override')
      ..writeln('  Widget build(BuildContext context) {')
      ..writeln('    return Scaffold(');
    if (background != null) {
      buffer.writeln('      backgroundColor: const $background,');
    }
    if (document.showAppBar) {
      buffer.writeln(
          '      appBar: AppBar(title: const Text(${dartString(document.title)})),');
    }
    buffer
      ..writeln('      body: LayoutBuilder(')
      ..writeln('        builder: (context, constraints) {')
      ..writeln('          final isMobile = constraints.maxWidth < '
          '${formatNumber(Breakpoints.tablet)};')
      ..writeln('          return SingleChildScrollView(')
      ..writeln('            padding: EdgeInsets.all(isMobile ? 16 : 24),')
      ..writeln('            child: Align(')
      ..writeln('              alignment: Alignment.topCenter,')
      ..writeln('              child: ConstrainedBox(')
      ..writeln('                constraints: const BoxConstraints('
          'maxWidth: ${formatNumber(Breakpoints.maxContentWidth)}),')
      ..writeln('                child: SizedBox(')
      ..writeln('                  width: double.infinity,')
      ..writeln('                  child: $root,')
      ..writeln('                ),')
      ..writeln('              ),')
      ..writeln('            ),')
      ..writeln('          );')
      ..writeln('        },')
      ..writeln('      ),')
      ..writeln('    );')
      ..writeln('  }')
      ..writeln('}');
    if (_usesAdaptiveRow) buffer.write(_adaptiveRowSource);
    if (_usesGrid) buffer.write(_responsiveGridSource);
    return buffer.toString();
  }

  CodeExpr _node(WidgetNode n) {
    switch (n.type) {
      case WidgetTypes.column:
        return CallCode('Column', [
          const Arg('mainAxisSize', RawCode('MainAxisSize.min')),
          Arg('mainAxisAlignment', RawCode('MainAxisAlignment.'
              '${WidgetCatalog.choiceOf(n, 'mainAxisAlignment', PropOptions.mainAxis)}')),
          Arg('crossAxisAlignment', RawCode('CrossAxisAlignment.'
              '${WidgetCatalog.choiceOf(n, 'crossAxisAlignment', PropOptions.columnCross)}')),
          Arg('spacing', _num(n.number('spacing'))),
          Arg('children', ListCode([for (final c in n.children) _node(c)])),
        ]);
      case WidgetTypes.row:
        return CallCode('Row', [
          Arg('mainAxisAlignment', RawCode('MainAxisAlignment.'
              '${WidgetCatalog.choiceOf(n, 'mainAxisAlignment', PropOptions.mainAxis)}')),
          Arg('crossAxisAlignment', RawCode('CrossAxisAlignment.'
              '${WidgetCatalog.choiceOf(n, 'crossAxisAlignment', PropOptions.rowCross)}')),
          Arg('spacing', _num(n.number('spacing'))),
          Arg(
            'children',
            ListCode([
              for (final c in n.children)
                CallCode('Flexible', [Arg('child', _node(c))]),
            ]),
          ),
        ]);
      case WidgetTypes.adaptiveRow:
        _usesAdaptiveRow = true;
        return CallCode('_AdaptiveRow', [
          Arg('breakpoint', _num(n.number('breakpoint', Breakpoints.tablet))),
          Arg('spacing', _num(n.number('spacing'))),
          Arg('children', ListCode([for (final c in n.children) _node(c)])),
        ]);
      case WidgetTypes.grid:
        _usesGrid = true;
        return CallCode('_ResponsiveGrid', [
          Arg('mobileColumns', RawCode('${_columns(n, 'mobileColumns')}')),
          Arg('tabletColumns', RawCode('${_columns(n, 'tabletColumns')}')),
          Arg('desktopColumns', RawCode('${_columns(n, 'desktopColumns')}')),
          Arg('spacing', _num(n.number('spacing'))),
          Arg('children', ListCode([for (final c in n.children) _node(c)])),
        ]);
      case WidgetTypes.container:
        {
          final color = _color(n.string('color'));
          final width = n.number('width');
          final height = n.number('height');
          return CallCode('Container', [
            if (width > 0) Arg('width', _num(width)),
            if (height > 0) Arg('height', _num(height)),
            Arg('padding', _edgeAll(n.number('padding'))),
            Arg(
              'decoration',
              CallCode('BoxDecoration', [
                if (color != null) Arg('color', RawCode(color)),
                Arg('borderRadius', _radius(n.number('borderRadius'))),
              ]),
            ),
            if (n.children.isNotEmpty) Arg('child', _node(n.children.first)),
          ]);
        }
      case WidgetTypes.card:
        {
          final color = _color(n.string('color'));
          return CallCode('Card', [
            const Arg('margin', RawCode('EdgeInsets.zero')),
            if (color != null) Arg('color', RawCode(color)),
            Arg('elevation', _num(n.number('elevation'))),
            Arg(
              'shape',
              CallCode('RoundedRectangleBorder', [
                Arg('borderRadius', _radius(n.number('borderRadius'))),
              ]),
            ),
            Arg(
              'child',
              CallCode('Padding', [
                Arg('padding', _edgeAll(n.number('padding'))),
                if (n.children.isNotEmpty)
                  Arg('child', _node(n.children.first)),
              ]),
            ),
          ]);
        }
      case WidgetTypes.text:
        {
          final color = _color(n.string('color'));
          final weight = WidgetCatalog.choiceOf(
              n, 'fontWeight', PropOptions.fontWeight);
          return CallCode('Text', [
            Arg.positional(RawCode(dartString(n.string('text')))),
            Arg('textAlign', RawCode('TextAlign.'
                '${WidgetCatalog.choiceOf(n, 'textAlign', PropOptions.textAlign)}')),
            Arg(
              'style',
              CallCode('TextStyle', [
                Arg('fontSize', _num(n.number('fontSize', 16))),
                Arg('fontWeight', RawCode(_fontWeight(weight))),
                if (color != null) Arg('color', RawCode(color)),
              ]),
            ),
          ]);
        }
      case WidgetTypes.button:
        return _button(n);
      case WidgetTypes.icon:
        {
          final color = _color(n.string('color'));
          return CallCode('Icon', [
            Arg.positional(RawCode(
                'Icons.${WidgetCatalog.choiceOf(n, 'icon', PropOptions.icons)}')),
            Arg('size', _num(n.number('size', 24))),
            if (color != null) Arg('color', RawCode(color)),
          ]);
        }
      case WidgetTypes.image:
        return CallCode('ClipRRect', [
          Arg('borderRadius', _radius(n.number('borderRadius'))),
          Arg(
            'child',
            CallCode('Image.network', [
              Arg.positional(RawCode(dartString(n.string('url')))),
              Arg('height', _num(n.number('height', 180))),
              const Arg('width', RawCode('double.infinity')),
              Arg('fit', RawCode('BoxFit.'
                  '${WidgetCatalog.choiceOf(n, 'fit', PropOptions.imageFit)}')),
            ]),
          ),
        ]);
      case WidgetTypes.textField:
        {
          final label = n.string('label');
          final hint = n.string('hint');
          return CallCode('TextField', [
            if (n.boolean('obscure'))
              const Arg('obscureText', RawCode('true')),
            Arg(
              'decoration',
              CallCode('InputDecoration', [
                if (label.isNotEmpty)
                  Arg('labelText', RawCode(dartString(label))),
                if (hint.isNotEmpty) Arg('hintText', RawCode(dartString(hint))),
                const Arg('border', RawCode('const OutlineInputBorder()')),
              ]),
            ),
          ]);
        }
      case WidgetTypes.divider:
        {
          final color = _color(n.string('color'));
          return CallCode('Divider', [
            Arg('thickness', _num(n.number('thickness', 1))),
            if (color != null) Arg('color', RawCode(color)),
          ]);
        }
      case WidgetTypes.spacer:
        {
          final size = _num(n.number('size', 16));
          return CallCode('SizedBox', [Arg('width', size), Arg('height', size)]);
        }
      default:
        final type = n.type.replaceAll('*/', '');
        return RawCode('const SizedBox.shrink() /* unsupported: $type */');
    }
  }

  CodeExpr _button(WidgetNode n) {
    final color = _color(n.string('color'));
    final variant =
        WidgetCatalog.choiceOf(n, 'variant', PropOptions.buttonVariant);
    final String widget;
    final List<Arg> style;
    switch (variant) {
      case 'elevated':
        widget = 'ElevatedButton';
        style = [
          if (color != null) Arg('backgroundColor', RawCode(color)),
          if (color != null)
            const Arg('foregroundColor', RawCode('Colors.white')),
        ];
      case 'outlined':
        widget = 'OutlinedButton';
        style = [
          if (color != null) Arg('foregroundColor', RawCode(color)),
          if (color != null)
            Arg('side', CallCode('BorderSide', [Arg('color', RawCode(color))])),
        ];
      case 'text':
        widget = 'TextButton';
        style = [if (color != null) Arg('foregroundColor', RawCode(color))];
      default:
        widget = 'FilledButton';
        style = [if (color != null) Arg('backgroundColor', RawCode(color))];
    }
    CodeExpr button = CallCode(widget, [
      const Arg('onPressed', RawCode('() {}')),
      if (style.isNotEmpty) Arg('style', CallCode('$widget.styleFrom', style)),
      Arg(
        'child',
        CallCode('Text', [
          Arg.positional(RawCode(dartString(n.string('label')))),
        ]),
      ),
    ]);
    if (n.boolean('fullWidth')) {
      button = CallCode('SizedBox', [
        const Arg('width', RawCode('double.infinity')),
        Arg('child', button),
      ]);
    }
    return button;
  }

  static CodeExpr _num(double value) => RawCode(formatNumber(value));

  static CodeExpr _edgeAll(double value) =>
      CallCode('EdgeInsets.all', [Arg.positional(_num(value))]);

  static CodeExpr _radius(double value) =>
      CallCode('BorderRadius.circular', [Arg.positional(_num(value))]);

  static int _columns(WidgetNode n, String key) {
    final value = n.number(key, 1).round();
    return value < 1 ? 1 : (value > 12 ? 12 : value);
  }

  static String? _color(String hex) {
    final value = parseHexColor(hex);
    if (value == null) return null;
    return 'Color(0x${value.toRadixString(16).padLeft(8, '0').toUpperCase()})';
  }

  static String _fontWeight(String weight) => switch (weight) {
        'medium' => 'FontWeight.w500',
        'semibold' => 'FontWeight.w600',
        'bold' => 'FontWeight.w700',
        _ => 'FontWeight.w400',
      };
}

const _adaptiveRowSource = '''

/// Shows children side by side on wide screens and stacks them on phones.
class _AdaptiveRow extends StatelessWidget {
  const _AdaptiveRow({
    required this.children,
    this.spacing = 16,
    this.breakpoint = 600,
  });

  final List<Widget> children;
  final double spacing;
  final double breakpoint;

  @override
  Widget build(BuildContext context) {
    return LayoutBuilder(
      builder: (context, constraints) {
        if (constraints.maxWidth < breakpoint) {
          return Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.stretch,
            spacing: spacing,
            children: children,
          );
        }
        return Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          spacing: spacing,
          children: [for (final child in children) Expanded(child: child)],
        );
      },
    );
  }
}
''';

const _responsiveGridSource = '''

/// Lays children out in a grid whose column count depends on screen width.
class _ResponsiveGrid extends StatelessWidget {
  const _ResponsiveGrid({
    required this.children,
    this.mobileColumns = 1,
    this.tabletColumns = 2,
    this.desktopColumns = 3,
    this.spacing = 16,
  });

  final List<Widget> children;
  final int mobileColumns;
  final int tabletColumns;
  final int desktopColumns;
  final double spacing;

  @override
  Widget build(BuildContext context) {
    final screenWidth = MediaQuery.sizeOf(context).width;
    final columns = screenWidth >= 1024
        ? desktopColumns
        : screenWidth >= 600
            ? tabletColumns
            : mobileColumns;
    return LayoutBuilder(
      builder: (context, constraints) {
        final available = constraints.maxWidth - spacing * (columns - 1);
        final itemWidth = available <= 0 ? 0.0 : (available / columns).floorToDouble();
        return Wrap(
          spacing: spacing,
          runSpacing: spacing,
          children: [
            for (final child in children)
              SizedBox(width: itemWidth, child: child),
          ],
        );
      },
    );
  }
}
''';
